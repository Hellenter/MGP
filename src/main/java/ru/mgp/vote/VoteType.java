package ru.mgp.vote;

public enum VoteType {
    /** Побеждает вариант с наибольшим числом голосов (ничья — случайно среди лидеров). */
    MOST_VOTES,
    /** Побеждает случайный вариант среди тех, за которые проголосовал хоть кто-то. */
    RANDOM_VOTED,
    /** Каждый голос добавляет вес (шанс) варианту, затем взвешенная случайность. */
    WEIGHTED,
    /** Без голосования: случайный вариант (с учётом weight). */
    NONE
}
